// A lab policy net as Codex's Monte zero net (KMRRing/Crates trumps-monte-net.js): each layer's weights (row-major, out × in) and
// biases as little-endian float32, base64; an M1 net (inputs "raw+part") carries its two belief nets the same way. Korbi, 27 Nov
// 2026: "replace currently deployed Monte with our most recent/strongest".
// usage: node lab/schafkopf/export-codex.mjs <net file from the repo root> <out .js> "<what it is, one line>"
import fs from "node:fs";

const [file, out, what] = process.argv.slice(2), j = JSON.parse(fs.readFileSync(file, "utf8"));
const b64 = xs => Buffer.from(Float32Array.from(xs).buffer).toString("base64");
const layersOf = n => n.layers.map(l => ({ n: l.b.length, k: l.w[0].length, w: b64(l.w.flat()), b: b64(l.b) }));
const source = file.split("/").pop().replace(/\.json$/, "");
const NET = {
  source, n_in: j.n_in, inputs: j.inputs || "raw", layers: layersOf(j),
  ...(j.beliefs ? { beliefs: Object.fromEntries(Object.entries(j.beliefs).map(([k, n]) => [k, { n_in: n.n_in, layers: layersOf(n) }])) } : {}),
};
const shape = n => [n.n_in, ...n.layers.map(l => l.n)].join(" → ");
fs.writeFileSync(out, `// Monte zero's policy net (lab KMRRing/Dandan ${file}, ${what}):
// inputs ${NET.inputs}: ${shape(NET)}, ReLU between${NET.beliefs ? `; with its belief nets over who holds the called ace, own ${shape(NET.beliefs.own)} and public ${shape(NET.beliefs.public)}` : ""};
// each layer's weights (row-major, out × in) and biases as little-endian float32, base64. Generated by the lab's
// lab/schafkopf/export-codex.mjs; replace it whole with a newer net, never by hand.
export const NET = ${JSON.stringify(NET)};
`);
console.log(`export-codex: ${source} → ${out} (${(fs.statSync(out).size / 1e6).toFixed(2)} MB)`);
